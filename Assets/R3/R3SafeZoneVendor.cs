using System;
using System.Collections.Generic;
using RoboRougelike.R4;
using UnityEngine;

namespace RoboRougelike.R3
{
    public readonly struct R3SafeZoneOffer
    {
        public readonly int Index, Price;
        public readonly R3PartKind Kind;
        public readonly R4WeaponKind Weapon;
        public readonly bool Sold;
        public R3SafeZoneOffer(int index,R3PartKind kind,R4WeaponKind weapon,int price,bool sold)
        {Index=index;Kind=kind;Weapon=weapon;Price=price;Sold=sold;}
    }

    public sealed partial class R3VehicleModel
    {
        public int SafeVendorStage {get;private set;}
        public int SafeVendorSeed {get;private set;}
        public int SafeVendorSoldMask {get;private set;}
        public int SafeVendorRevision {get;private set;}
        readonly HashSet<int> safeVendorExtraSold=new HashSet<int>();
        public void PrepareSafeZoneVendor(int seed)
        {
            if(CreativeMode||SafeZoneLastCompleted<=0||SafeVendorStage==SafeZoneLastCompleted)return;
            SafeVendorStage=SafeZoneLastCompleted;SafeVendorSeed=seed;SafeVendorSoldMask=0;SafeVendorRevision=1;safeVendorExtraSold.Clear();
        }
        public IReadOnlyList<R3SafeZoneOffer> SafeZoneVendorOffers()
        {
            if(CreativeMode||SafeVendorStage<=0||SafeVendorStage!=SafeZoneLastCompleted)return Array.Empty<R3SafeZoneOffer>();
            return new SafeVendorOfferList(this,Math.Max(0,Economy.SafeVendorOfferCount));
        }
        // Offers after the original four are generated by index, so even a
        // very large configured count does not allocate or iterate eagerly.
        sealed class SafeVendorOfferList : IReadOnlyList<R3SafeZoneOffer>
        {
            static readonly R3PartKind[] drives={R3PartKind.Wheel,R3PartKind.OmniDrive,R3PartKind.CrawlerTrack};
            static readonly R3PartKind[] passives={R3PartKind.Battery,R3PartKind.EnergyRegenerator};
            static readonly R3PartKind[] actives={R3PartKind.RepairPulse,R3PartKind.Overdrive};
            static readonly R4WeaponKind[] weapons={R4WeaponKind.Basic,R4WeaponKind.Automatic,R4WeaponKind.Heavy};
            readonly R3VehicleModel owner;readonly R3PartKind[] first;readonly R4WeaponKind firstWeapon;
            public int Count {get;}
            public SafeVendorOfferList(R3VehicleModel model,int count)
            {
                owner=model;Count=count;var random=new System.Random(model.SafeVendorSeed);
                first=new[]{drives[random.Next(drives.Length)],R3PartKind.Gun,passives[random.Next(passives.Length)],actives[random.Next(actives.Length)]};
                firstWeapon=weapons[random.Next(weapons.Length)];
                if(model.SafeVendorRevision>=1&&random.Next(2)==0)first[2]=R3PartKind.Armor;
            }
            public R3SafeZoneOffer this[int index]
            {
                get
                {
                    if(index<0||index>=Count)throw new ArgumentOutOfRangeException(nameof(index));
                    R3PartKind kind;R4WeaponKind weapon;
                    if(index<4){kind=first[index];weapon=kind==R3PartKind.Gun?firstWeapon:R4WeaponKind.Basic;}
                    else
                    {
                        var random=new System.Random(unchecked(owner.SafeVendorSeed^(int)((uint)index*2654435761u)));
                        int category=index%4;
                        kind=category==0?drives[random.Next(drives.Length)]:category==1?R3PartKind.Gun:
                            category==2?(random.Next(2)==0?R3PartKind.Armor:passives[random.Next(passives.Length)]):actives[random.Next(actives.Length)];
                        weapon=kind==R3PartKind.Gun?weapons[random.Next(weapons.Length)]:R4WeaponKind.Basic;
                    }
                    float factor=owner.Economy.SafeVendorPriceMultiplier;
                    if(float.IsNaN(factor)||float.IsInfinity(factor))factor=.5f;
                    int price=(int)Math.Min(int.MaxValue,Math.Max(1d,Math.Ceiling(owner.BasePrice(kind,weapon)*(double)Math.Max(0,factor))));
                    bool sold=index<4?(owner.SafeVendorSoldMask&(1<<index))!=0:owner.safeVendorExtraSold.Contains(index);
                    return new R3SafeZoneOffer(index,kind,weapon,price,sold);
                }
            }
            public IEnumerator<R3SafeZoneOffer> GetEnumerator(){for(int i=0;i<Count;i++)yield return this[i];}
            System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator()=>GetEnumerator();
        }
        public bool TryPurchaseSafeZoneOffer(int index)
        {
            var offers=SafeZoneVendorOffers();if(index<0||index>=offers.Count)return false;
            var offer=offers[index];int firstNewItem=inventory.Count;
            if(offer.Sold||!PurchaseToInventoryAtPrice(offer.Kind,offer.Weapon,R3WheelStyle.Offroad,R3ArmorShape.Cube,offer.Price))return false;
            if(offer.Kind==R3PartKind.Armor)
            {
                // Allocate at most the pack price across its actual physical
                // blocks; standard purchases and all other parts are untouched.
                int remaining=offer.Price;
                for(int i=firstNewItem;i<inventory.Count;i++)
                {
                    var part=inventory[i];int cap=Math.Min(remaining,DismantleFullValue(part));
                    part.HasDismantleCap=true;part.DismantleCap=cap;remaining-=cap;
                    part.Source="Pakiet sprzedawcy — ograniczony odzysk";
                }
            }
            if(index<4)SafeVendorSoldMask|=1<<index;else safeVendorExtraSold.Add(index);return true;
        }
    }
}
