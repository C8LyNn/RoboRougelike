#!/usr/bin/env python3
"""Executed source-level regression on ORIGINAL Codex #383 original Unity XML.

Synthetic receipts exercise forgery/mismatch negatives. Original native XML
is read byte-for-byte from the real Git object, not generated by this suite.
"""
import copy
import json
from pathlib import Path
import subprocess
import sys
import unittest
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(HERE))
import native_receipt_triage as triage

GAMEPLAY = "203a0805251ed28293888e43f2d49f0df63767c6"
REPORT = "f92c873bb1e397a598b133e107ae704e15f86768"
GOOD = "Demo.Test_Pass"
BAD = "Demo.Test_Original_Fail"


def xml(tests):
    counts = {a: sum(1 for _, status in tests if status == a)
              for a in ("Passed", "Failed", "Inconclusive", "Skipped")}
    root = ET.Element("test-run", {
        "result": "Failed(Child)" if counts["Failed"] or counts["Skipped"] or counts["Inconclusive"] else "Passed",
        "total": str(len(tests)), "passed": str(counts["Passed"]),
        "failed": str(counts["Failed"]), "inconclusive": str(counts["Inconclusive"]),
        "skipped": str(counts["Skipped"]),
    })
    for name, state in tests:
        leaf = ET.SubElement(root, "test-case", {"fullname": name, "result": state})
        if state == "Failed":
            ET.SubElement(ET.SubElement(leaf, "failure"), "message").text = "expected one but got zero"
        if state == "Skipped":
            ET.SubElement(ET.SubElement(leaf, "reason"), "message").text = "HQ conditional"
    return b'<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(root)


def process(mode, exit_code, filtered=False, source=GAMEPLAY):
    args = ["-runTests", "-testPlatform", mode, "-testResults", "Native.xml"]
    if filtered:
        args += ["-testFilter", "Demo.Test_Original_Fail"]
    return json.dumps({"phase": mode, "source": source, "exitCode": exit_code,
                       "arguments": args, "stage": "FixtureNativeReceipt"}).encode()


def samples():
    return {
        "full_edit": (xml([(GOOD, "Passed"), (BAD, "Failed")]), process("EditMode", 2)),
        "full_play": (xml([(GOOD, "Passed")]), process("PlayMode", 0)),
        "target_edit": (xml([(GOOD, "Passed")]), process("EditMode", 0, True)),
        "failure_retest": (xml([(BAD, "Passed")]), process("EditMode", 0, True)),
    }


class SourceTriageTests(unittest.TestCase):
    def test_01_real_codex_full_edit_fail_play_pass_retest_pass(self):
        out = triage.inspect(ROOT, REPORT, GAMEPLAY)
        self.assertEqual(out["status"], "HOLD_FULL_NATIVE_REGRESSION")
        self.assertEqual(out["gameplay_sha"], GAMEPLAY)
        e, p = out["full_edit"], out["full_play"]
        self.assertEqual((e["total"], e["passed"], e["failed"], e["skipped"]),
                         (1330, 1327, 2, 1))
        self.assertEqual((p["total"], p["passed"], p["failed"], p["skipped"]),
                         (474, 474, 0, 0))
        self.assertEqual(out["targeted_edit"]["passed"], 20)
        self.assertEqual(out["failure_retest"]["passed"], 2)
        self.assertEqual(e["exit_code"], 2)
        self.assertEqual(p["exit_code"], 0)
        self.assertEqual(out["g1_assessment"], "HOLD")
        self.assertEqual(out["independent_native_qa"], "NOT_RUN_BY_THIS_TOOL")
        self.assertEqual(len(out["original_full_edit_failed_but_retest_passed"]), 2)
        self.assertFalse(out["original_full_edit_failed_without_green_retest"])
        self.assertTrue(any("Camera275NativeTests" in x["fullname"]
                            for x in e["failed_tests"]))
        self.assertTrue(any("MapgenRC1IntegrationTests" in x["fullname"]
                            for x in e["failed_tests"]))
        self.assertTrue(any("B0124EnemyAiNegativeEditModeTests" in x["fullname"]
                            for x in e["skipped_tests"]))
        print("ORIGINAL_CODEX_383_XML_1330_EDIT_TWO_FAILED_ONE_SKIPPED_474_PLAY_HOLD")

    def test_02_original_native_evidence_from_real_git_provenance(self):
        triage.validate_source(ROOT, REPORT, GAMEPLAY)
        raw = triage.original_blob(ROOT, REPORT, "EditMode.xml", triage.MAX_XML)
        self.assertIn(b'failed="2"', raw[:350])
        self.assertGreater(len(raw), 1000000)
        self.assertRaises(triage.ReceiptError, triage.validate_source,
                          ROOT, "0" * 40, GAMEPLAY)
        print("REAL_GIT_NATIVE_RECEIPT_SOURCE_SHA_AND_XML_BYTES_VERIFIED")

    def test_03_synthetic_filtered_green_does_not_override_full_red(self):
        out = triage.evaluate_receipts(samples(), GAMEPLAY)
        self.assertEqual(out["status"], "HOLD_FULL_NATIVE_REGRESSION")
        self.assertEqual(out["original_full_edit_failed_but_retest_passed"], [BAD])
        self.assertEqual(out["g1_assessment"], "HOLD")
        print("FILTERED_RETEST_GREEN_CANNOT_OVERRIDE_FAILED_FULL_EDIT_RED")

    def test_04_forged_process_gameplay_sha_fails_closed(self):
        data = samples()
        data["full_edit"] = (data["full_edit"][0], process("EditMode", 2, source="f" * 40))
        with self.assertRaisesRegex(triage.ReceiptError, "PROCESS_GAMEPLAY_SHA_MISMATCH"):
            triage.evaluate_receipts(data, GAMEPLAY)
        print("FORGED_OR_STALE_NATIVE_SOURCE_SHA_FAIL_CLOSED")

    def test_05_zero_exit_with_failed_nunit_xml_fails_closed(self):
        data = samples()
        data["full_edit"] = (data["full_edit"][0], process("EditMode", 0))
        with self.assertRaisesRegex(triage.ReceiptError, "ZERO_NATIVE_EXIT_WITH_FAILED_XML"):
            triage.evaluate_receipts(data, GAMEPLAY)
        print("NATIVE_ZERO_EXIT_CANNOT_MASK_FAILED_XML")

    def test_06_nonzero_exit_with_green_xml_fails_closed(self):
        data = samples()
        data["full_play"] = (data["full_play"][0], process("PlayMode", 2))
        with self.assertRaisesRegex(triage.ReceiptError, "NONZERO_NATIVE_EXIT_WITH_GREEN_XML"):
            triage.evaluate_receipts(data, GAMEPLAY)
        print("NATIVE_FAILED_PROCESS_CANNOT_MASK_GREEN_XML")

    def test_07_wrong_mode_or_undisclosed_filter_fails_closed(self):
        with self.assertRaisesRegex(triage.ReceiptError, "PROCESS_MODE_OR_EXIT_INVALID"):
            triage.parse_process(process("PlayMode", 0), "EditMode", False, GAMEPLAY)
        with self.assertRaisesRegex(triage.ReceiptError, "UNDECLARED_OR_UNEXPECTED_TARGET_FILTER"):
            triage.parse_process(process("EditMode", 0, True), "EditMode", False, GAMEPLAY)
        with self.assertRaisesRegex(triage.ReceiptError, "UNDECLARED_OR_UNEXPECTED_TARGET_FILTER"):
            triage.parse_process(process("EditMode", 0), "EditMode", True, GAMEPLAY)
        print("FULL_VS_FILTERED_NATIVE_TEST_BOUNDARY_ENFORCED")

    def test_08_duplicate_or_missing_testcase_fails_closed(self):
        payload = xml([(GOOD, "Passed"), (GOOD, "Passed")])
        with self.assertRaisesRegex(triage.ReceiptError, "DUPLICATE"):
            triage.parse_nunit(payload, "dup.xml")
        payload = xml([("", "Passed")])
        with self.assertRaisesRegex(triage.ReceiptError, "MISSING_OR_DUPLICATE"):
            triage.parse_nunit(payload, "empty.xml")
        print("DUPLICATE_OR_UNIDENTIFIED_NUNIT_LEAF_REJECTED")

    def test_09_forged_root_counts_truncated_xml_dtd_rejected(self):
        raw = xml([(GOOD, "Passed")])
        with self.assertRaisesRegex(triage.ReceiptError, "ROOT_LEAF"):
            triage.parse_nunit(raw.replace(b'total="1"', b'total="2"'), "root.xml")
        with self.assertRaisesRegex(triage.ReceiptError, "MALFORMED"):
            triage.parse_nunit(raw[:-30], "cut.xml")
        with self.assertRaisesRegex(triage.ReceiptError, "XML_DTD_FORBIDDEN"):
            triage.parse_nunit(raw.replace(b"<test-run", b"<!DOCTYPE p>\n<test-run"), "dtd.xml")
        print("TAMPERED_XML_COUNTER_TRUNCATION_DTD_FAIL_CLOSED")

    def test_10_missing_receipts_and_nonancestor_cannot_green(self):
        d = samples()
        del d["full_play"]
        with self.assertRaisesRegex(triage.ReceiptError, "INCOMPLETE"):
            triage.evaluate_receipts(d, GAMEPLAY)
        with self.assertRaises(triage.ReceiptError):
            triage.validate_source(ROOT, GAMEPLAY, REPORT)
        print("MISSING_NATIVE_STAGE_AND_REVERSED_PROVENANCE_FAIL_CLOSED")

    def test_11_actual_cli_exit2_and_machine_readable_original_failures(self):
        args = [sys.executable, str(HERE / "native_receipt_triage.py"),
                "--repo", str(ROOT), "--evidence-commit", REPORT,
                "--gameplay-sha", GAMEPLAY]
        p = subprocess.run(args, text=True, capture_output=True)
        self.assertEqual(p.returncode, 2, p.stderr)
        j = json.loads(p.stdout)
        self.assertEqual(j["status"], "HOLD_FULL_NATIVE_REGRESSION", j)
        self.assertEqual(len(j["full_edit"]["failed_tests"]), 2)
        self.assertIn("evidence_commit_sha", j)
        self.assertEqual(j["full_edit"]["source_sha"], GAMEPLAY)
        print("ACTUAL_CODEX_NATIVE_FAILED_XML_PRODUCES_NONZERO_CLI_STATUS_AND_JSON")

    def test_12_cli_invalid_original_source_sha_fails_closed(self):
        args = [sys.executable, str(HERE / "native_receipt_triage.py"),
                "--repo", str(ROOT), "--evidence-commit", REPORT,
                "--gameplay-sha", "0" * 40]
        p = subprocess.run(args, text=True, capture_output=True)
        self.assertEqual(p.returncode, 2)
        j = json.loads(p.stdout)
        self.assertEqual(j["status"], "FAIL_CLOSED_UNVERIFIABLE_NATIVE_RECEIPT", j)
        print("FORGED_GAMEPLAY_SHA_RETURNS_NONZERO_FAIL_CLOSED_JSON")


if __name__ == "__main__":
    unittest.main(verbosity=2)
