"""Converts the Blender-space block QA (cells, ports, patches) into the Unity / BUILD001 contract.

Axis mapping (semantic, same as the FBX export: -Z forward, Y up):  right = Blender +X = Unity +X,
up = Blender +Z = Unity +Y, forward = Blender -Y = Unity +Z   ->   Unity(x, y, z) = Blender(x, z, -y).
BUILD001 tangent frame (BuildSocketGeometry.Tangents): u = face.x != 0 ? up : right; v = Cross(face, u).
Offset / HalfSize are in cell units (1 = 0.55 m) like BuildSocket; the face plane is cell + face * 0.5.
Writes integration/R4_BLOCKS_UNITY.json and integration/R4BlockCatalog.cs.txt (a C# draft, not compiled).
usage: python3 make_unity_catalog.py <R4Blocks dir>
"""
import json, os, sys

ROOT = sys.argv[1]
G, H = 0.55, 0.26
ORDER = ["Cube", "Wedge", "Tetra", "InnerCorner", "CornerWedge", "RoundEdge", "RoundCorner", "HalfBlock", "HalfWedge", "Cylinder",
         "Beam2", "Beam3", "LongWedge", "Plate2x2", "TrussCube", "Pyramid", "Dome", "Cone", "HexColumn", "OctColumn", "RoundTop", "Arch",
         "Step", "CoveEdge", "CornerL3", "Tee4", "Slab2x2", "BigCube2", "Plate1x2", "WideWedge"]
DIRS_B = {"right": (1, 0, 0), "left": (-1, 0, 0), "up": (0, 0, 1), "down": (0, 0, -1), "forward": (0, -1, 0), "back": (0, 1, 0)}
BIT = {"right": 0, "left": 1, "up": 2, "down": 3, "forward": 4, "back": 5}


def U(v): return (v[0], v[2], -v[1])
def dot(a, b): return sum(x*y for x, y in zip(a, b))
def cross(a, b): return (a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0])
def frame_b(n):   # build_blocks.frame (Blender): u = Z x n (or X x n when n is vertical), v = n x u
    up = (0, 0, 1) if abs(n[2]) < 0.9 else (1, 0, 0); u = cross(up, n); l = dot(u, u)**0.5; u = tuple(x/l for x in u); return u, cross(n, u)
def tang_u(face): u = (0, 1, 0) if face[0] != 0 else (1, 0, 0); return u, cross(face, u)


def rnd(v, k=4): return [round(x + 0.0, k) for x in v]


out = {"axis_mapping": "Unity(x,y,z) = Blender(x,z,-y); right=+X, up=+Y, forward=+Z", "tangents": "BUILD001: u = face.x!=0 ? up : right; v = Cross(face,u)",
       "units": "cells (1 = 0.55 m); face plane = cell + face*0.5", "blocks": []}
for k in ORDER:
    mid = "R4B_" + k; q = json.load(open(os.path.join(ROOT, mid, mid + "_QA.json"), encoding="utf-8"))
    cells = [list(map(int, U(c))) for c in q["cells"]]
    socks = []
    for p in q["ports"]:
        nb = DIRS_B[p["dir"]]; face = tuple(int(x) for x in U(nb)); cell = tuple(int(x) for x in U(p["cell"]))
        ub, vb = frame_b(nb); hb = p["half"]; ob = p["offset"]
        # patch centre and extents in Blender, then in Unity
        cb = [p["cell"][i] + nb[i]*0.5 + ub[i]*ob[0] + vb[i]*ob[1] for i in range(3)]                  # cells
        ext_b = [abs(ub[i])*hb[0] + abs(vb[i])*hb[1] for i in range(3)]
        cu = U(cb); ext_u = (ext_b[0], ext_b[2], ext_b[1])
        tu, tv = tang_u(face); rel = [cu[i] - cell[i] - face[i]*0.5 for i in range(3)]
        off = (dot(rel, tu), dot(rel, tv)); half = (dot(ext_u, tuple(abs(x) for x in tu)), dot(ext_u, tuple(abs(x) for x in tv)))
        assert abs(off[0]) + half[0] <= 0.5001 and abs(off[1]) + half[1] <= 0.5001, (mid, p)
        socks.append({"cell": list(cell), "face": list(face), "dir": p["dir"], "kind": p["kind"], "offset": rnd(off), "half": rnd(half)})
    bonds = [[list(map(int, U(a))), list(map(int, U(b)))] for a, b in q["bonds"]]
    mask = 0
    for s in socks:
        if s["cell"] == [0, 0, 0]: mask |= 1 << BIT[s["dir"]]
    out["blocks"].append({"id": mid, "kind": k, "cells": cells, "bonds": bonds, "contact_mask_anchor": mask,
                          "full_ports": sum(1 for s in socks if s["kind"] == "full"), "sockets": socks,
                          "mount_modules": any(s["kind"] == "full" for s in socks), "note": q.get("note"),
                          "fbx": f"{mid}/{mid}.fbx", "colliders": f"{mid}/{mid}_colliders.glb"})
os.makedirs(os.path.join(ROOT, "integration"), exist_ok=True)
json.dump(out, open(os.path.join(ROOT, "integration", "R4_BLOCKS_UNITY.json"), "w", encoding="utf-8"), indent=1)

V = lambda v: f"new Vector3Int({v[0]},{v[1]},{v[2]})"
F = lambda x: f"{x:.4f}f"
cs = ["// GENERATED by Tools/ModelFactory/R4Blocks/scripts/make_unity_catalog.py - DRAFT for integration, not compiled (.cs.txt).",
      "// Unity axes; BUILD001 units (cells). Full ports: HalfSize .47 like R3BuildValidation. Partial ports: smaller patches.",
      "using UnityEngine;", "using B01.BUILD001;", "",
      "public static class R4BlockCatalog", "{",
      "    public struct Entry { public string Id; public Vector3Int[] Cells; public BuildSocket[] Sockets; public bool[] PartialSocket; public (Vector3Int,Vector3Int)[] Bonds; public int ContactMaskAnchor; }",
      "    public static readonly Entry[] All = {"]
for b in out["blocks"]:
    socks = ", ".join(f"new BuildSocket({V(s['cell'])},{V(s['face'])},BuildSocketKind.Structural,new Vector2({F(s['half'][0])},{F(s['half'][1])}),new Vector2({F(s['offset'][0])},{F(s['offset'][1])}))" for s in b["sockets"])
    part = ", ".join("true" if s["kind"] != "full" else "false" for s in b["sockets"])
    bonds = ", ".join(f"({V(a)},{V(c)})" for a, c in b["bonds"])
    cs.append(f"        new Entry{{Id=\"{b['id']}\",Cells=new[]{{{', '.join(V(c) for c in b['cells'])}}},ContactMaskAnchor={b['contact_mask_anchor']},")
    cs.append(f"            Sockets=new[]{{{socks}}},")
    cs.append(f"            PartialSocket=new[]{{{part}}}, Bonds=new (Vector3Int,Vector3Int)[]{{{bonds}}}}},")
cs += ["    };", "}", ""]
open(os.path.join(ROOT, "integration", "R4BlockCatalog.cs.txt"), "w", encoding="utf-8").write("\n".join(cs))
print("blocks", len(out["blocks"]), "sockets", sum(len(b["sockets"]) for b in out["blocks"]))
