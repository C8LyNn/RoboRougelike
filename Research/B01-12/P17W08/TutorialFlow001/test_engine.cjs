'use strict';
// Execute actual original deterministic engine, not a mock. No Unity runtime.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const crypto = require('node:crypto');
const path = require('node:path');
const { STEPS, initial, view, transition } = require('./tutorial_engine.js');
const root = __dirname;
const manifest = JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
for (const [name, pin] of Object.entries(manifest.files)) {
  const bytes = fs.readFileSync(path.join(root, name));
  assert.equal(bytes.length, pin.bytes, 'bytes '+name);
  assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), pin.sha256, 'hash '+name);
}
const rows=[];
function check(name, test) { try { test(); rows.push({name, pass:true}) } catch(e){ rows.push({name,pass:false,error:String(e.stack||e)}); process.stderr.write('FAIL '+name+' '+e.message+'\n') } }
const act=(id,phase,action)=>({type:'ACTION',id,phase,action});
const apply=(s,evt)=>transition(s,evt);
const step=(s,action,phase,id)=>apply(s,act(id === undefined ? 'event-'+s.revision : id,phase||STEPS[s.index].phase,action||STEPS[s.index].action));
const beginning=initial();
check('initial index 0',()=>assert.equal(beginning.index,0));
check('initial status active',()=>assert.equal(beginning.status,'active'));
check('initial no history',()=>assert.equal(beginning.history.length,0));
check('fixed 6 steps',()=>assert.equal(STEPS.length,6));
check('view first step',()=>assert.equal(view(beginning).current.id,'garage_core'));
check('view progress 0%',()=>assert.equal(view(beginning).progress,0));
check('immutable step definitions',()=>assert.ok(Object.isFrozen(STEPS)&&STEPS.every(Object.isFrozen)));
check('history cannot be forged',()=>assert.throws(()=>view({...beginning,index:1}),/INVALID_FLOW_STATE/));
check('invalid unsupported version fails closed',()=>assert.throws(()=>view({...beginning,version:2}),/INVALID_FLOW_STATE/));
check('invalid skipped mandatory fails closed',()=>assert.throws(()=>view({...beginning,index:1,history:[{step:'garage_core',result:'skipped'}]}),/INVALID_FLOW_HISTORY/));
check('negative index fails closed',()=>assert.throws(()=>view({...beginning,index:-1}),/INVALID_FLOW_STATE/));
check('duplicate receipt state fails closed',()=>assert.throws(()=>view({...beginning,receipts:['a','a']}),/INVALID_FLOW_RECEIPTS/));
check('invalid event null rejected',()=>assert.equal(apply(beginning,null).effect.code,'INVALID_EVENT'));
check('invalid event string rejected',()=>assert.equal(apply(beginning,'ACTION').effect.code,'INVALID_EVENT'));
check('unsupported event type rejected',()=>assert.equal(apply(beginning,{type:'JUMP',index:5}).effect.code,'INVALID_EVENT'));
check('wrong phase rejected',()=>assert.equal(step(beginning,'select_core','combat','a').effect.code,'WRONG_ACTION'));
check('wrong action rejected',()=>assert.equal(step(beginning,'mount_wheel','garage','a').effect.code,'WRONG_ACTION'));
check('wrong action leaves original same reference',()=>assert.equal(step(beginning,'mount_wheel','garage','a').state,beginning));
check('skip mandatory rejected',()=>assert.equal(apply(beginning,{type:'SKIP'}).effect.code,'REQUIRED_STEP'));
check('back at start rejected',()=>assert.equal(apply(beginning,{type:'BACK'}).effect.code,'AT_START'));
check('restart before done rejected',()=>assert.equal(apply(beginning,{type:'RESTART'}).effect.code,'NOT_COMPLETE'));
for (const id of ['', 'space bad', 'a'.repeat(65), '..', '\n', 7, undefined]) {
  check('invalid receipt '+JSON.stringify(id),()=>assert.equal(step(beginning,'select_core','garage',id===undefined?undefined:id).effect.code,id===undefined?'STEP_DONE':'INVALID_RECEIPT'));
}
const p1=apply(beginning,act('first','garage','select_core')).state;
check('valid action step index',()=>assert.equal(p1.index,1));
check('original input unchanged',()=>assert.equal(beginning.index,0));
check('action records history',()=>assert.deepEqual(p1.history,[{step:'garage_core',result:'done'}]));
check('action records receipt',()=>assert.deepEqual(p1.receipts,['first']));
check('revision increments exactly once',()=>assert.equal(p1.revision,1));
check('progress 17%',()=>assert.equal(view(p1).progress,17));
check('repeat old receipt rejected even if next action',()=>assert.equal(apply(p1,act('first','garage','mount_wheel')).effect.code,'DUPLICATE'));
check('wrong next action no advance',()=>assert.equal(apply(p1,act('second','garage','inspect_weapon')).state,p1));
const p2=apply(p1,act('second','garage','mount_wheel')).state;
check('second mandatory completed',()=>assert.equal(p2.index,2));
check('optional step exposed',()=>assert.equal(view(p2).current.optional,true));
const p3=apply(p2,{type:'SKIP'}).state;
check('optional skip advances',()=>assert.equal(p3.index,3));
check('skip outcome saved',()=>assert.equal(p3.history[2].result,'skipped'));
check('skip does not add receipt',()=>assert.equal(p3.receipts.length,2));
check('action in old phase blocked after skip',()=>assert.equal(apply(p3,act('third','garage','inspect_weapon')).effect.code,'WRONG_ACTION'));
const p4=apply(p3,act('fourth','combat','fire_a')).state;
check('combat fire advances',()=>assert.equal(p4.index,4));
check('next optional visible',()=>assert.equal(view(p4).current.id,'combat_dodge'));
const p5=apply(p4,act('fifth','combat','dodge')).state;
check('combat dodge performed',()=>assert.equal(p5.history[4].result,'done'));
check('reward cannot be skipped',()=>assert.equal(apply(p5,{type:'SKIP'}).effect.code,'REQUIRED_STEP'));
check('wrong context at result blocked',()=>assert.equal(apply(p5,act('sixth','garage','claim_reward')).effect.code,'WRONG_ACTION'));
const p6=apply(p5,act('sixth','result','claim_reward')).state;
check('complete status',()=>assert.equal(p6.status,'complete'));
check('complete index 6',()=>assert.equal(p6.index,6));
check('complete progress 100%',()=>assert.equal(view(p6).progress,100));
check('complete current null',()=>assert.equal(view(p6).current,null));
check('complete effect',()=>assert.equal(apply(p5,act('sixth','result','claim_reward')).effect.code,'FLOW_COMPLETE'));
check('post-complete action ignored',()=>assert.equal(apply(p6,act('seventh','result','claim_reward')).effect.code,'ALREADY_COMPLETE'));
check('post-complete skip ignored',()=>assert.equal(apply(p6,{type:'SKIP'}).effect.code,'ALREADY_COMPLETE'));
check('post-complete restart allowed',()=>assert.equal(apply(p6,{type:'RESTART'}).state.index,0));
check('post-complete back to final',()=>assert.equal(apply(p6,{type:'BACK'}).state.index,5));
check('back truncates history',()=>assert.equal(apply(p6,{type:'BACK'}).state.history.length,5));
check('back clears receipts to allow replay',()=>assert.equal(apply(p6,{type:'BACK'}).state.receipts.length,0));
check('back does not change source complete',()=>assert.equal(p6.status,'complete'));
check('back text is not gameplay rollback',()=>assert.match(apply(p6,{type:'BACK'}).effect.text,/nie są odwracane/));
check('back then retry final accepted',()=>{let b=apply(p6,{type:'BACK'}).state;assert.equal(apply(b,act('sixth','result','claim_reward')).state.status,'complete')});
check('skip optional + back restores required marker',()=>{let b=apply(p3,{type:'BACK'}).state;assert.equal(view(b).current.id,'garage_weapon');assert.equal(b.history.length,2)});
check('reset on active clears state',()=>{let b=apply(p5,{type:'RESET'}).state;assert.equal(b.index,0);assert.deepEqual(b.history,[]);assert.deepEqual(b.receipts,[])});
check('reset still monotonic revision',()=>assert.equal(apply(p5,{type:'RESET'}).state.revision,p5.revision+1));
check('restart clears completed state',()=>assert.equal(apply(p6,{type:'RESTART'}).state.status,'active'));
check('invalid receipt code cannot progress',()=>assert.equal(apply(beginning,{type:'ACTION',phase:'garage',action:'select_core',id:'foo bar'}).state,beginning));
check('state immutability of history snapshots',()=>{let b=apply(p5,{type:'BACK'}).state;b.history[0].step='edited';assert.equal(p5.history[0].step,'garage_core')});
check('status forged fails closed',()=>assert.throws(()=>view({...beginning,status:'complete'}),/INVALID_FLOW_STATE/));
check('untrusted mutated history fails closed',()=>assert.throws(()=>view({...p3,history:[...p3.history.slice(0,2),{step:'garage_weapon',result:'x'}]}),/INVALID_FLOW_HISTORY/));
check('same valid event after reset accepted',()=>{let b=apply(p1,{type:'RESET'}).state;assert.equal(apply(b,act('first','garage','select_core')).effect.code,'STEP_DONE')});
const report={package:'B01-12-TUTORIALFLOW-001/R1',environment:{node:process.version},total:rows.length,passed:rows.filter(r=>r.pass).length,failed:rows.filter(r=>!r.pass),cases:rows};
fs.writeFileSync(path.join(root,'node-results.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({total:report.total,passed:report.passed,failed:report.failed.length,environment:report.environment}));
if (report.failed.length) process.exit(1);
