#!/usr/bin/env python3
"""Actual Playwright Chromium against verified original byte sources. No localhost needed."""
import hashlib,json,os,sys
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
manifest=json.loads((ROOT/'manifest.json').read_text(encoding='utf-8'))
for name,pin in manifest['files'].items():
    data=(ROOT/name).read_bytes()
    if len(data)!=pin['bytes'] or hashlib.sha256(data).hexdigest()!=pin['sha256']:
        print('FAIL_CLOSED '+name);sys.exit(2)
html=(ROOT/'demo.html').read_text(encoding='utf-8').replace('<script src="route_engine.js"></script>','<script>\n'+(ROOT/'route_engine.js').read_text(encoding='utf-8')+'\n</script>').replace('<script src="ui.js"></script>','<script>\n'+(ROOT/'ui.js').read_text(encoding='utf-8')+'\n</script>')
results=[]
def check(name,test):
    yes=bool(test);results.append({'name':name,'ok':yes})
    if not yes: print('FAIL',name)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=None if os.getenv('GITHUB_ACTIONS') else os.getenv('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    for width,height in [(320,720),(768,1024),(1280,720),(1920,1080)]:
        page=browser.new_page(viewport={'width':width,'height':height});errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
        page.set_content(html,wait_until='load')
        snap=lambda:json.loads(page.locator('#snapshot').inner_text())
        prefix=str(width)
        check(prefix+' initial garage',snap()['route']=='garage')
        check(prefix+' seven routes',page.locator('#routes button').count()==7)
        check(prefix+' no back',page.locator('#back').is_disabled())
        check(prefix+' no forward',page.locator('#forward').is_disabled())
        page.locator('[data-route=parts]').click()
        check(prefix+' parts nav',snap()['route']=='parts')
        check(prefix+' breadcrumb',page.locator('#crumbs').inner_text()=='Garaż / Części')
        page.locator('[data-route=inspector]').click()
        check(prefix+' inspector nav',snap()['route']=='inspector')
        check(prefix+' inspector crumb',page.locator('#crumbs').inner_text()=='Garaż / Części / Inspektor')
        page.locator('#back').click()
        check(prefix+' back parts',snap()['route']=='parts')
        page.locator('#forward').click()
        check(prefix+' forward inspector',snap()['route']=='inspector')
        page.locator('#dirty').click()
        check(prefix+' dirty on',snap()['dirty'] is True)
        page.locator('[data-route=settings]').click()
        check(prefix+' guard shown',not page.locator('#overlay').is_hidden())
        check(prefix+' screen not changed',snap()['route']=='inspector')
        check(prefix+' pending settings',snap()['guard']['route']=='settings')
        page.keyboard.press('Escape')
        check(prefix+' escape closes',page.locator('#overlay').is_hidden())
        check(prefix+' cancel preserves dirty',snap()['dirty'] is True)
        page.locator('[data-route=settings]').click()
        page.locator('#discard').click()
        check(prefix+' accept navigates',snap()['route']=='settings')
        check(prefix+' accept clean',snap()['dirty'] is False)
        page.locator('#back').click()
        check(prefix+' back to inspector',snap()['route']=='inspector')
        page.locator('[data-route=arena]').click()
        check(prefix+' fork path',snap()['route']=='arena' and snap()['history'][-1]=='arena')
        check(prefix+' forward removed',page.locator('#forward').is_disabled())
        page.locator('#dirty').click();page.keyboard.press('Alt+ArrowLeft')
        check(prefix+' guarded keyboard back',snap()['guard']['type']=='BACK')
        page.locator('#stay').click()
        check(prefix+' stay preserves route',snap()['route']=='arena')
        page.locator('#dirty').click()
        check(prefix+' dirty off',snap()['dirty'] is False)
        page.keyboard.press('Alt+ArrowLeft')
        check(prefix+' keyboard back',snap()['route']=='inspector')
        page.locator('#reset').click()
        check(prefix+' reset garage',snap()['route']=='garage' and snap()['revision']==0)
        check(prefix+' ARIA status',page.locator('#status').get_attribute('role')=='status')
        check(prefix+' no horizontal overflow',page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'))
        check(prefix+' no JS errors',len(errors)==0)
        if width==1280: page.screenshot(path=str(ROOT/'evidence-1280x720.png'),full_page=True)
        page.close()
    browser.close()
output={'total':len(results),'pass':sum(x['ok'] for x in results),'fail':sum(not x['ok'] for x in results),'cases':results}
(ROOT/'browser-results.json').write_text(json.dumps(output,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('CHROMIUM',output['pass'],'/',output['total'],'PASS' if not output['fail'] else 'FAIL')
sys.exit(1 if output['fail'] else 0)
