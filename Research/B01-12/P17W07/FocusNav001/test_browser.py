#!/usr/bin/env python3
"""Original-byte Chromium acceptance for FOCUSNAV-001; explicitly not Unity/native."""
import hashlib,json,os,sys
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
manifest=json.loads((ROOT/'manifest.json').read_text(encoding='utf-8'))
for f in ['focus_engine.js','focusnav.html','test_engine.cjs','test_browser.py']:
 raw=(ROOT/f).read_bytes()
 if manifest['source_sha256'].get(f)!=hashlib.sha256(raw).hexdigest() or manifest['source_bytes'].get(f)!=len(raw):
  print('FAIL_CLOSED: source hash/length mismatch '+f,file=sys.stderr);sys.exit(2)
checks=[];errors=[]
def ck(tag,label,condition):
 checks.append({'case':tag+'/'+label,'pass':bool(condition)})
 if not condition:print('RED',tag,label,file=sys.stderr)
def focus(page):return page.evaluate('document.activeElement?.id')
def state(page):return page.evaluate('window.__B01FocusTest.snapshot')
html=(ROOT/'focusnav.html').read_text(encoding='utf-8').replace('<script src="focus_engine.js"></script>','<script>'+ (ROOT/'focus_engine.js').read_text(encoding='utf-8') +'</script>')
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 for w,h in [(320,720),(768,1024),(1280,720),(1920,1080)]:
  tag=str(w);page=browser.new_page(viewport={'width':w,'height':h});page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content(html)
  ck(tag,'initial_page',state(page)['panel']=='garage')
  ck(tag,'initial_focus',focus(page)=='control-build')
  ck(tag,'initial_invariant',page.evaluate('window.__B01FocusTest.invariant'))
  ck(tag,'cards_garage_6',page.locator('button.card').count()==6)
  ck(tag,'no_horizontal_overflow',page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
  page.keyboard.press('ArrowRight')
  ck(tag,'right_navigation',focus(page)=='control-rotate')
  page.keyboard.press('ArrowDown')
  ck(tag,'down_navigation',focus(page)=='control-paint')
  page.keyboard.press('ArrowLeft')
  ck(tag,'left_navigation',focus(page)=='control-inventory')
  page.keyboard.press('ArrowUp')
  ck(tag,'up_navigation',focus(page)=='control-build')
  page.keyboard.press('Enter')
  ck(tag,'enter_opens_modal',state(page)['modal'] and focus(page)=='confirm')
  ck(tag,'inert_underlay',page.locator('#background').evaluate('(e)=>e.inert') is True)
  ck(tag,'modal_has_aria',page.locator('[role="dialog"]').get_attribute('aria-modal')=='true')
  page.keyboard.press('ArrowRight')
  ck(tag,'modal_right',focus(page)=='cancel')
  page.keyboard.press('Tab')
  ck(tag,'modal_tab_trap',focus(page)=='confirm')
  page.keyboard.press('Shift+Tab')
  ck(tag,'modal_shift_tab_trap',focus(page)=='cancel')
  ck(tag,'modal_state_invariant',page.evaluate('window.__B01FocusTest.invariant'))
  page.keyboard.press('Escape')
  ck(tag,'escape_closes_modal',not state(page)['modal'] and focus(page)=='control-build')
  ck(tag,'background_unlocked',page.locator('#background').evaluate('(e)=>!e.inert'))
  page.locator('button[data-panel="run"]').click()
  ck(tag,'switch_run',state(page)['panel']=='run' and focus(page)=='control-run-stats')
  page.keyboard.press('ArrowRight')
  ck(tag,'run_focus_map',focus(page)=='control-run-map')
  page.locator('button[data-panel="garage"]').click()
  ck(tag,'garage_focus_memory',focus(page)=='control-build')
  page.locator('#toggle').click()
  ck(tag,'disable_focus_fallback',state(page)['focus']=='rotate' and 'build' in state(page)['disabled'] and focus(page)=='control-rotate')
  ck(tag,'disabled_is_real',page.locator('#control-build').is_disabled())
  page.locator('button[data-panel="reward"]').click()
  ck(tag,'reward_focus',focus(page)=='control-reward-armor')
  page.locator('button[data-panel="garage"]').click()
  ck(tag,'garage_memory_fallback',focus(page)=='control-rotate')
  page.locator('#restore').click()
  ck(tag,'restore_enables_all',not state(page)['disabled'] and not page.locator('#control-build').is_disabled())
  page.locator('#control-launch').click()
  ck(tag,'pointer_opens_modal',state(page)['modal'] and focus(page)=='confirm')
  page.locator('#confirm').click()
  ck(tag,'confirm_closes_modal',not state(page)['modal'] and state(page)['lastEvent']=='Zatwierdzono' and focus(page)=='control-launch')
  page.locator('#control-repair').click();page.locator('#cancel').click()
  ck(tag,'cancel_restores_selected',not state(page)['modal'] and focus(page)=='control-repair' and state(page)['lastEvent']=='Anulowano')
  page.locator('#reset').click()
  ck(tag,'reset_deterministic',state(page)['panel']=='garage' and state(page)['focus']=='build' and state(page)['sequence']==0)
  ck(tag,'postreset_invariant',page.evaluate('window.__B01FocusTest.invariant'))
  ck(tag,'no_horizontal_overflow_end',page.evaluate('document.documentElement.scrollWidth<=window.innerWidth'))
  if w==1280:page.screenshot(path=str(ROOT/'evidence-1280x720.png'),full_page=True)
  page.close()
 browser.close()
result={'package':'B01-12-FOCUSNAV-001/R1','total':len(checks),'pass':sum(c['pass'] for c in checks),'fail':[c['case'] for c in checks if not c['pass']],'js_errors':errors,'environment':'Linux Chromium via Playwright; NOT Unity','checks':checks}
(ROOT/'browser-results.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(json.dumps({k:v for k,v in result.items() if k!='checks'},indent=2))
sys.exit(0 if not result['fail'] and not errors else 1)
