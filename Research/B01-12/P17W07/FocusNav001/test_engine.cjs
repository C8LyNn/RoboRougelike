'use strict';
const assert=require('node:assert/strict');
const {FocusRouter,panels}=require('./focus_engine.js');
let n=0;const check=(name,fn)=>{fn();n++;};
const r=new FocusRouter();
check('initial invariant',()=>assert.equal(r.invariant(),true));
check('initial garage',()=>assert.equal(r.focus,'build'));
check('right',()=>assert.deepEqual(r.move('ArrowRight'),{ok:true,focus:'rotate'}));
check('down',()=>assert.equal(r.move('ArrowDown').focus,'paint'));
check('left',()=>assert.equal(r.move('ArrowLeft').focus,'inventory'));
check('up',()=>assert.equal(r.move('ArrowUp').focus,'build'));
check('edge',()=>assert.equal(r.move('ArrowLeft').reason,'edge'));
check('invalid direction',()=>assert.equal(r.move('F13').reason,'invalid-direction'));
check('switch run',()=>assert.equal(r.switchPanel('run').focus,'run-stats'));
check('switch back',()=>assert.equal(r.switchPanel('garage').focus,'build'));
check('disable focused',()=>{assert.equal(r.setEnabled('build',false).ok,true);assert.equal(r.focus,'rotate')});
check('disabled cannot focus',()=>assert.equal(r.focusControl('build').ok,false));
check('disabled excluded',()=>{const a=r.move('ArrowLeft');assert.notEqual(a.focus,'build');assert.equal(r.invariant(),true);r.focusControl('rotate')});
check('memory restore after disable',()=>{r.switchPanel('reward');assert.equal(r.switchPanel('garage').focus,'rotate')});
check('enable restores eligibility',()=>assert.equal(r.setEnabled('build',true).ok,true));
check('unexpected id refused',()=>assert.equal(r.setEnabled('garbage',true).reason,'unknown-control'));
check('bad type refused',()=>assert.equal(r.setEnabled('build',1).reason,'invalid-enabled'));
check('unknown panel refused',()=>assert.equal(r.switchPanel('__proto__').ok,false));
check('activate opens modal',()=>{assert.equal(r.activate().ok,true);assert.equal(r.focus,'confirm')});
check('modal blocks panel switch',()=>assert.equal(r.switchPanel('run').reason,'modal-trap'));
check('modal blocks underlay focus',()=>assert.equal(r.focusControl('launch').reason,'modal-trap'));
check('modal right',()=>assert.equal(r.move('ArrowRight').focus,'cancel'));
check('modal edge',()=>assert.equal(r.move('ArrowRight').reason,'edge'));
check('modal refuses duplicate',()=>assert.equal(r.openDialog().reason,'already-modal'));
check('modal escape returns original',()=>{assert.equal(r.closeDialog().focus,'rotate');assert.equal(r.invariant(),true)});
check('modal close twice denied',()=>assert.equal(r.closeDialog().reason,'no-modal'));
check('accept confirmation',()=>{r.activate('repair');assert.equal(r.activate('confirm').accepted,true);assert.equal(r.focus,'repair')});
check('cancel confirmation',()=>{r.activate('launch');assert.equal(r.activate('cancel').accepted,false);assert.equal(r.focus,'launch')});
check('disabled fallback in modal',()=>{r.activate();r.setEnabled('launch',false);assert.equal(r.closeDialog().focus,'build')});
check('all panels have unique ids',()=>{const nodes=Object.values(panels).flat();assert.equal(new Set(nodes.map(x=>x.id)).size,nodes.length)});
check('prevent last disable',()=>{const q=new FocusRouter();for(const x of panels.garage.slice(1))assert.equal(q.setEnabled(x.id,false).ok,true);assert.equal(q.setEnabled('build',false).reason,'last-focusable');assert.equal(q.invariant(),true)});
check('snapshot is not writable reference',()=>{const s=r.snapshot();s.memory.garage='bogus';s.disabled.push('new');assert.notEqual(r.memory.garage,'bogus');assert.equal(r.disabled.has('new'),false)});
check('disabled preserved across panels',()=>{assert.equal(r.disabled.has('launch'),true);r.switchPanel('reward');r.switchPanel('garage');assert.equal(r.disabled.has('launch'),true)});
check('snapshot deterministic disabled ordering',()=>{r.setEnabled('paint',false);r.setEnabled('build',false);assert.deepEqual(r.snapshot().disabled,['build','launch','paint'])});
check('fixed reset into alive fallback',()=>assert.equal(r.invariant(),true));
console.log(JSON.stringify({suite:'node-pure-focus-reducer',passed:n,failed:0,platform:process.version}));
