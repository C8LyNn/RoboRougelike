    public static int StageCount => Stages.Length;
    public static int TotalLayouts => Stages.Length*4;
    [MenuItem("B01/Enemy Staging/Generate all 12 isolated formation scenes")]
    public static void GenerateAll()
    {
      string sceneFolder=OutputRoot+"/Scenes";
      // Fail closed BEFORE changing the open Unity scene or writing output.
      // Never overwrite manually modified scene data.
      for(int s=0;s<Stages.Length;s++)for(int n=1;n<=4;n++)
      {
        string path=ScenePath(Stages[s].Id,n);
        if(File.Exists(path))throw new IOException("Refusing to overwrite staged scene: "+path);
      }
      Directory.CreateDirectory(sceneFolder);
      var originalScene=SceneManager.GetActiveScene();
      foreach(var stage in Stages)for(int count=1;count<=4;count++)
      {
        // Additive + restore active scene protects the receiver's unrelated work.
        var scene=EditorSceneManager.NewScene(NewSceneSetup.EmptyScene,NewSceneMode.Additive);
        try
        {
          if(!SceneManager.SetActiveScene(scene))
            throw new InvalidOperationException("Cannot activate disposable staging scene");
          GenerateStage(stage,count);
          if(!EditorSceneManager.SaveScene(scene,ScenePath(stage.Id,count)))
            throw new IOException("Unity failed to persist enemy staging scene: "+stage.Id+" / "+count);
        }
        finally
        {
          SceneManager.SetActiveScene(originalScene);
          EditorSceneManager.CloseScene(scene,true);
        }
      }
      AssetDatabase.Refresh();
      Debug.Log("B01-24 W03: generated "+TotalLayouts+" isolated Unity preview scenes; original R5 and Codex gameplay untouched.");
    }
    private static string ScenePath(string id,int count)=>
      OutputRoot+"/Scenes/"+id+"-S"+count+".unity";

    private static void GenerateStage(StageLayout stage,int count)
    {
      GameObject root=new GameObject("B01-24 W03 | "+stage.Id+" | spawnCount="+count);
      MakeCube(root.transform,"Ground (preview only)",new Vector3(0,-0.11f,0),
        new Vector3(82,0.2f,82));
      MakeCube(root.transform,"North barrier",new Vector3(0,2,42),new Vector3(86,4,2));
      MakeCube(root.transform,"South barrier",new Vector3(0,2,-42),new Vector3(86,4,2));
      MakeCube(root.transform,"West barrier",new Vector3(-42,2,0),new Vector3(2,4,82));
      MakeCube(root.transform,"East barrier",new Vector3(42,2,0),new Vector3(2,4,82));
      if(stage.Arena==0)
      {
        for(int side=-1;side<=1;side+=2)
        {
          MakeCube(root.transform,"Scrap press",new Vector3(side*10,.85f,0),new Vector3(3,1.7f,5));
          MakeCube(root.transform,"Wreck cover",new Vector3(side*21,.6f,13),new Vector3(5,1.2f,2));
          MakeCube(root.transform,"Low cover",new Vector3(side*20,.6f,-13),new Vector3(4,1.2f,3));
        }
      }
      else if(stage.Arena==1)
      {
        MakeCube(root.transform,"Western rock",new Vector3(-26,1,-5),new Vector3(4,2,6));
        MakeCube(root.transform,"Eastern rock",new Vector3(26,.7f,8),new Vector3(6,1.4f,3));
      }
      else if(stage.Arena==2)
      {
        for(int side=-1;side<=1;side+=2)for(int row=-1;row<=1;row+=2)
          MakeCube(root.transform,"Factory hall",new Vector3(side*17,2.5f,row*7),new Vector3(10,5,9));
        MakeCube(root.transform,"Western link",new Vector3(-31,1.5f,0),new Vector3(3,3,14));
        MakeCube(root.transform,"Eastern link",new Vector3(31,1.5f,0),new Vector3(3,3,14));
      }
      else throw new InvalidOperationException("Unknown source arena kind");
      // Original R5Arena places these two hazard triggers in every map.
      MakeMarker(root.transform,"WARNING-only hazard(-6,-6)",new Vector3(-6,.1f,-6));
      MakeMarker(root.transform,"WARNING-only hazard(6,8)",new Vector3(6,.1f,8));
      MakeCylinder(root.transform,"Player spawn at original R5Arena.PlayerSpawn",new Vector3(0,.7f,-22),new Vector3(3,0.7f,3));
      Vector2[] spots=stage.Positions[count-1];
      if(spots.Length!=count)throw new InvalidOperationException("Source roster count does not match formation");
      for(int i=0;i<spots.Length;i++)
        MakeCylinder(root.transform,"ENEMY_"+(i+1)+"_of_"+count,
          new Vector3(spots[i].x,.75f,spots[i].y),new Vector3(5,.75f,5));
      var cam=new GameObject("Top-down evidence camera");
      cam.transform.SetParent(root.transform,false);
      cam.transform.position=new Vector3(0,95,0);
      cam.transform.rotation=Quaternion.Euler(90,0,0);
      cam.tag="MainCamera";
      Camera camera=cam.AddComponent<Camera>();
      camera.orthographic=true;camera.orthographicSize=48;camera.nearClipPlane=.1f;camera.farClipPlane=200;
      var sun=new GameObject("Staging light");
      sun.transform.SetParent(root.transform,false);
      sun.transform.rotation=Quaternion.Euler(50,-30,0);
      Light light=sun.AddComponent<Light>();
      light.type=LightType.Directional; light.intensity=1f;
    }
    private static GameObject MakeCube(Transform parent,string name,Vector3 pos,Vector3 scale)
    {
      var go=GameObject.CreatePrimitive(PrimitiveType.Cube);
      go.name=name; go.transform.SetParent(parent,false);
      go.transform.localPosition=pos;go.transform.localScale=scale;
      return go;
    }
    private static GameObject MakeCylinder(Transform parent,string name,Vector3 pos,Vector3 scale)
    {
      var go=GameObject.CreatePrimitive(PrimitiveType.Cylinder);
      go.name=name;go.transform.SetParent(parent,false);
      go.transform.localPosition=pos;go.transform.localScale=scale;
      return go;
    }
    private static void MakeMarker(Transform parent,string name,Vector3 pos)
    {
      var go=GameObject.CreatePrimitive(PrimitiveType.Sphere);
      go.name=name;go.transform.SetParent(parent,false);
      go.transform.localPosition=pos;go.transform.localScale=new Vector3(1,.15f,1);
      go.GetComponent<Collider>().enabled=false; // markers must not change staging collision geometry
    }
